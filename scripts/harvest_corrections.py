#!/usr/bin/env python3
"""Turn down-voted answers into REVIEW DRAFTS — never into changes.

The +1 layer's correction loop, with the human kept in it: user corrections
are evidence, not edits. This script reads the feedback audit lines
(`stage=feedback`, written by `data_agent/feedback.py`) from the runtime's
log group, keeps the down-votes, and writes a review bundle a person turns
into a pull request — a fix to a metric description, a table card or the
wiki, plus a regression case so the same question cannot silently regress
again. Nothing here touches `semantic/`, `verified_queries/` or the eval
cases; the bundle lands in a directory of its own (git-ignored).

    ./.venv/bin/python scripts/harvest_corrections.py --days 7
    ./.venv/bin/python scripts/harvest_corrections.py --days 1 --out review/

Per down-vote the bundle has: the question, the persona, which tier answered
(verified / metric / free_sql — where to look first), the user's correction
as UNTRUSTED quoted text, and a draft eval case with the expectation left
for the reviewer to write (a correction is a claim, not a golden). The
summary table gives the down-rate per tier — the same numbers the dashboard
shows, so a reviewer starts from the bucket that is decaying.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
QUERY = """
fields @timestamp, audit.verdict as verdict, audit.provenance as tier,
       audit.principal as principal, audit.question as question,
       audit.correction as correction, audit.turn_id as turn_id,
       audit.provenance_mix.0 as first_tier
| filter audit.stage = "feedback"
| sort @timestamp desc
| limit 10000
"""

# Where a reviewer should look first, per tier.
WHERE = {
    "verified": "the verified query's SQL or its question (verified_queries/*.yaml)",
    "metric": "the metric definition or its description (semantic/<scenario>.yaml)",
    "free_sql": "the table card / wiki the model read (semantic/cards, semantic/wiki)",
    "none": "no statement ran — the routing or the refusal wording (prompt / cards)",
}


def _runtime_log_group(region: str, name: str) -> str:
    import boto3

    ctl = boto3.client("bedrock-agentcore-control", region_name=region)
    for page in ctl.get_paginator("list_agent_runtimes").paginate():
        for r in page.get("agentRuntimes", []):
            if r["agentRuntimeName"] == name:
                return f"/aws/bedrock-agentcore/runtimes/{r['agentRuntimeId']}-DEFAULT"
    sys.exit(f"no agent runtime named {name!r}")


def fetch(region: str, log_group: str, days: float) -> list[dict]:
    import boto3

    logs = boto3.client("logs", region_name=region)
    end = int(time.time())
    qid = logs.start_query(
        logGroupName=log_group, startTime=end - int(days * 86400), endTime=end, queryString=QUERY
    )["queryId"]
    while True:
        res = logs.get_query_results(queryId=qid)
        if res["status"] in ("Complete", "Failed", "Cancelled", "Timeout"):
            break
        time.sleep(1.5)  # nosemgrep: arbitrary-sleep -- Logs Insights poll backoff
    if res["status"] != "Complete":
        sys.exit(f"Logs Insights query {res['status']}")
    return [{c["field"]: c["value"] for c in row} for row in res["results"]]


def _quote(text: str | None) -> str:
    """Untrusted text as an inert block: no fence can be closed from inside."""
    if not text:
        return "_(none)_"
    safe = text.replace("```", "ʼʼʼ")
    return "```text\n" + safe + "\n```"


def summarize(rows: list[dict]) -> dict[str, dict]:
    total, down = Counter(), Counter()
    for r in rows:
        total[r.get("tier") or "none"] += 1
        if r.get("verdict") == "down":
            down[r.get("tier") or "none"] += 1
    return {
        t: {"feedback": total[t], "down": down[t], "down_rate": down[t] / total[t]}
        for t in sorted(total)
    }


def bundle(rows: list[dict], days: float) -> tuple[str, list[dict]]:
    """(review markdown, draft eval cases) — pure, for the tests."""
    stats = summarize(rows)
    downs = [r for r in rows if r.get("verdict") == "down"]
    md = [
        f"# Correction review — last {days:g} day(s)",
        "",
        "Generated by scripts/harvest_corrections.py. Every item below is EVIDENCE for a",
        "reviewer, not a change: decide whether an asset is wrong, fix it in a pull",
        "request, and add the regression case (with an expectation YOU write).",
        "",
        "| Tier | Feedback | Down | Down-rate |",
        "|---|---:|---:|---:|",
    ]
    md += [
        f"| {t} | {s['feedback']} | {s['down']} | {s['down_rate']:.0%} |" for t, s in stats.items()
    ]
    cases = []
    for i, r in enumerate(downs, 1):
        tier = r.get("tier") or "none"
        md += [
            "",
            f"## {i}. {tier} · {r.get('principal')} · {r.get('@timestamp')}",
            "",
            f"**Question** {_quote(r.get('question'))}",
            "",
            f"**User's correction (untrusted)** {_quote(r.get('correction'))}",
            "",
            f"**Look first at:** {WHERE.get(tier, WHERE['none'])}",
        ]
        cases.append(
            {
                "id": f"corr-{(r.get('turn_id') or str(i))[:12]}",
                "category": "corrections",
                "persona": "TODO-map-from-principal:" + str(r.get("principal")),
                "prompt": r.get("question") or "",
                "expect": {"TODO": "write the expectation after deciding the right answer"},
                "_source": {"tier": tier, "turn_id": r.get("turn_id")},
            }
        )
    return "\n".join(md) + "\n", cases


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=float, default=7)
    ap.add_argument("--region", default=os.environ.get("AGENT_REGION", "us-west-2"))
    ap.add_argument("--runtime-name", default="duckdb_analyst")
    ap.add_argument("--log-group", default="")
    ap.add_argument("--out", default=str(ROOT / "corrections-review"))
    args = ap.parse_args()
    group = args.log_group or _runtime_log_group(args.region, args.runtime_name)
    rows = fetch(args.region, group, args.days)
    md, cases = bundle(rows, args.days)
    out = Path(args.out) / dt.date.today().isoformat()
    out.mkdir(parents=True, exist_ok=True)
    (out / "review.md").write_text(md, encoding="utf-8")
    import yaml

    (out / "draft-cases.yaml").write_text(
        "# DRAFTS for review — not loaded by the eval runner until a human moves them\n"
        + yaml.safe_dump(cases, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    print(json.dumps({"feedback": len(rows), "down": len(cases), "bundle": str(out),
                      "by_tier": summarize(rows)}, indent=1))  # fmt: skip
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
